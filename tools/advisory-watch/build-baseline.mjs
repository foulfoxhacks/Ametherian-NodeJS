#!/usr/bin/env node
/**
 * Build docs/vulnerability-baseline.json from an OSV cache and classes.json.
 *
 *   node tools/advisory-watch/build-baseline.mjs <osv-cache.json>
 *
 * The OSV cache is the JSON written by `watch.mjs --write-cache` (or any
 * { "<package>": [OSV records] } file). Fails if an advisory is unmapped or a
 * mapped advisory no longer exists, so the baseline cannot drift silently.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { summarize } from './lib.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const cachePath = process.argv[2];
if (!cachePath) {
  console.error('usage: build-baseline.mjs <osv-cache.json>');
  process.exit(2);
}
const cache = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
const { classes } = JSON.parse(fs.readFileSync(new URL('./classes.json', import.meta.url), 'utf8'));

const classOf = new Map();
for (const [name, c] of Object.entries(classes)) {
  for (const id of c.advisories) {
    if (classOf.has(id)) throw new Error(`${id} is mapped to both ${classOf.get(id)} and ${name}`);
    classOf.set(id, name);
  }
}

const entries = [];
const seen = new Set();
for (const [pkg, records] of Object.entries(cache)) {
  for (const s of summarize(records)) {
    seen.add(s.ghsa);
    const cls = classOf.get(s.ghsa);
    if (!cls) throw new Error(`Unmapped advisory ${s.ghsa} (${pkg}): ${s.summary}`);
    const c = classes[cls];
    entries.push({ ...s, package: pkg, class: cls, cwe: c.cwe, status: c.status, control: c.control, tests: c.tests });
  }
}
const stale = [...classOf.keys()].filter((id) => !seen.has(id));
if (stale.length) throw new Error(`Mapped advisories missing from OSV data: ${stale.join(', ')}`);

entries.sort((a, b) => a.package.localeCompare(b.package) || a.published.localeCompare(b.published) || a.ghsa.localeCompare(b.ghsa));
const counts = entries.reduce((acc, e) => ((acc[e.status] = (acc[e.status] ?? 0) + 1), acc), {});
const out = {
  $comment: 'Generated by tools/advisory-watch/build-baseline.mjs. Do not edit by hand; edit classes.json.',
  generatedAt: new Date().toISOString(),
  sources: ['OSV (https://osv.dev), which aggregates the GitHub Advisory Database', 'CVE IDs as listed in NIST NVD (https://nvd.nist.gov)'],
  packages: Object.keys(cache),
  counts: { total: entries.length, ...counts },
  advisories: entries,
};
fs.writeFileSync(`${root}docs/vulnerability-baseline.json`, `${JSON.stringify(out, null, 2)}\n`);
console.log(`baseline: ${entries.length} advisories`, counts);
